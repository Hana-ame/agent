// ============================================================================
// bus_txn_pkg：事务级抽象（第 3 层，最顶层）——定义简单到就是结构体
// ============================================================================
// 设计意图：使用方（testbench / 上层的验证场景）只需要关心"一个事务长什么样"，
// 不需要知道 AXI 的五通道、握手、clocking 等任何协议细节。
//
// 就像写 C 代码里定义两个 struct 一样，一眼读完：
//   txn_t  —— 我要发一个什么事务（含 pause 等控制字段）
//   rsp_t  —— 我收到了什么结果
//
// 层次关系：
//   第 3 层  txn_t / rsp_t        ← 本文件（纯数据，无协议、无函数）
//      ↓  由 axi_txn_host 展开
//   第 2 层  AXI 握手时序
//      ↓
//   第 1 层  AXI 五通道信号 / 桥 / APB
// ============================================================================
`ifndef BUS_TXN_PKG_SV
`define BUS_TXN_PKG_SV

// ============================================================================
// 数据位宽配置
// ============================================================================
// txn_t.data / rsp_t.data 的位宽由 TXN_DW 宏决定（默认 32）。
// 支持 DW=64 等配置：编译时加 -DTXN_DW=64。
// 这样事务抽象层与 DUT 的 DW 参数保持一致，避免数据截断。
//
// 背景：此前硬编码 32 位，导致 DW=64 配置下经 txn_t 的数据被截断
// （tb_param_sv 参数矩阵测试发现，tb_dw64_sv 绕过 txn_t 验证了
//  桥与从机本身在 DW=64 下完全正确）。
// ============================================================================
`ifndef TXN_DW
  `define TXN_DW 32
`endif

package bus_txn_pkg;

    // ------------------------------------------------------------------
    // 一个事务的描述（纯数据，像 C struct）
    // ------------------------------------------------------------------
    typedef struct packed {
        bit            write;   // 1=写, 0=读
        bit [7:0]      addr;    // 地址
        bit [`TXN_DW-1:0] data;  // 写数据（读时忽略），位宽由 TXN_DW 配置
        bit [7:0]      pause;   // 本事务完成后空闲几拍（0=立刻下一个）
        bit            same;    // 写事务：AW 与 W 是否同拍发送
        bit            exp_err; // 期望错误响应（1=期望 SLVERR，用于越界向量）
    } txn_t;

    // ------------------------------------------------------------------
    // 一个事务的结果（纯数据，像 C struct）
    // ------------------------------------------------------------------
    typedef struct packed {
        bit [`TXN_DW-1:0] data;  // 读回数据（写时回显写入值），位宽由 TXN_DW 配置
        bit [1:0]      resp;    // 实际响应编码
        bit [7:0]      idle;    // 被 pause 的空闲拍计数（可观测）
    } rsp_t;

endpackage

`endif // BUS_TXN_PKG_SV